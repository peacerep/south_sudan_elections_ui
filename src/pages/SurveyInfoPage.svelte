<section class="survey-method-section" aria-labelledby="method-title">
  <div>
    <p class="section-number">Method</p>
    <h2 id="method-title">How the figures are produced</h2>
  </div>
  <dl class="survey-method-list">
    <div><dt>Percentages</dt><dd>Unweighted shares of valid responses. Unanswered and blank cases are excluded from the percentage and reported alongside detailed results.</dd></div>
    <div><dt>Survey waves</dt><dd>Seven cross-sectional rounds conducted between 2021 and 2026. The exact period is shown with each result.</dd></div>
    <div><dt>Maps</dt><dd>Points represent named survey locations, not respondent addresses. Blank areas were not surveyed and do not indicate zero responses.</dd></div>
    <div><dt>Question wording</dt><dd>Some answer choices changed as the electoral timetable changed. Where this affects comparison, results are presented wave by wave.</dd></div>
  </dl>
