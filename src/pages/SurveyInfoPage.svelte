<section class="survey-overview" aria-labelledby="overview-title">
  <div>
    <p class="section-number">Survey overview</p>
    <h2 id="overview-title">Recording everyday experiences and views of peace</h2>
  </div>
  <div class="survey-overview-copy">
    <p>The Perceptions of Peace in South Sudan series records daily experiences of safety and views on peace and conflict, elections, governance and security arrangements, trust in public authorities, civic space, national identity, social cohesion, displacement, humanitarian assistance and the regional effects of the war in Sudan.</p>
    <p>The research is led by Dr Jan Pospisil in collaboration with Detcro, the United States Institute of Peace and partners. It is a key component of PeaceRep’s South Sudan programme.</p>
    <p>Wave 7 added 4,526 interviews conducted in two phases: February–April and August–September 2026.</p>
  </div>
</section>

<section class="survey-info-section" aria-labelledby="reading-title">
  <p class="section-number">How to read the evidence</p>
  <h2 id="reading-title">Four things to keep in mind</h2>
  <div class="survey-info-grid">
    <article><h3>Surveyed places, not a national estimate</h3><p>The results describe respondents in the locations covered by the survey. They should not be read as estimates for every person or every area of South Sudan.</p></article>
    <article><h3>Different people in each period</h3><p>Each wave interviewed a new cross-section. A trend shows how responses differed between survey periods, not how the same people changed their minds.</p></article>
    <article><h3>Expectations are not predictions</h3><p>When respondents say violence, fraud or war is likely, they are reporting a perception. The survey does not predict what will happen.</p></article>
    <article><h3>Questions are shown separately</h3><p>Comparisons between two questions do not establish that the same individual gave both answers unless the analysis explicitly says so.</p></article>
  </div>
</section>

